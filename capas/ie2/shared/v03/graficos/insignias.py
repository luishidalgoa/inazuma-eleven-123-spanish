def palabra(texto, juego, hueco=None):
    """Matriz de caracteres '#', '+', '.' para el texto."""
    letras, h0 = JUEGOS[juego]
    hueco = h0 if hueco is None else hueco
    cols = []
    for i, ch in enumerate(texto):
        g = np.array([list(r) for r in letras[ch]])
        if i:
            cols.append(np.full((g.shape[0], hueco), '.'))
        cols.append(g)
    return np.concatenate(cols, 1)
